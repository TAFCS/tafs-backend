import { BadRequestException } from '@nestjs/common';
import type { IJwtStaffPayload } from '../auth/interfaces/jwt-payload.interface';

/**
 * TAFSD-605: small helpers every EC service shares.
 */

/** `campus_ids=1,2` or `campus_ids=1&campus_ids=2` both arrive as [1, 2]. */
export const toIntArray = ({ value }: { value: unknown }) => {
    if (value == null || value === '') return undefined;
    const parts = (Array.isArray(value) ? value : [value]).flatMap((v) => String(v).split(','));
    return parts.map((p) => p.trim()).filter(Boolean).map(Number);
};

/** `statuses=A,B` or repeated keys, as an upper-cased string array. */
export const toUpperStringArray = ({ value }: { value: unknown }) => {
    if (value == null || value === '') return undefined;
    const parts = (Array.isArray(value) ? value : [value]).flatMap((v) => String(v).split(','));
    return parts.map((p) => p.trim().toUpperCase()).filter(Boolean);
};

/** Who did it, for audit rows and `created_by` columns. */
export function actorOf(user: Pick<IJwtStaffPayload, 'username' | 'sub'> | undefined): string {
    return String(user?.username || user?.sub || 'system').slice(0, 100);
}

/** The name printed on documents ("generated by"). */
export function actorNameOf(user: Pick<IJwtStaffPayload, 'fullName' | 'username' | 'sub'> | undefined): string {
    return String(user?.fullName || user?.username || user?.sub || 'system').slice(0, 100);
}

/**
 * EC stores one spelling of an academic year: `YYYY-YYYY`, end = start + 1.
 * `2026-27` is accepted and widened.
 */
export function normalizeEcAcademicYear(raw: string | null | undefined): string {
    const text = String(raw ?? '').trim();
    const m = /^(\d{4})\s*-\s*(\d{2}|\d{4})$/.exec(text);
    if (!m) throw new BadRequestException(`Academic year "${text}" must look like 2026-2027`);
    const start = Number(m[1]);
    // A two-digit end is the last two digits of start + 1 (so 2099-00 is 2099-2100).
    const ok = m[2].length === 2 ? (start + 1) % 100 === Number(m[2]) : Number(m[2]) === start + 1;
    if (!ok) throw new BadRequestException(`Academic year "${text}" must span one year, e.g. ${start}-${start + 1}`);
    return `${start}-${start + 1}`;
}

/** Fee-head names are stored trimmed, single-spaced and upper-cased. */
export function normalizeEcName(raw: string): string {
    return String(raw ?? '').trim().replace(/\s+/g, ' ').toUpperCase();
}

/**
 * Months in the order of the school year (Aug first), duplicates dropped.
 * Fee heads store their months this way so the UI can print them as-is.
 */
export function normalizeEcMonths(months: number[]): number[] {
    const unique = [...new Set(months.map(Number))];
    for (const m of unique) {
        if (!Number.isInteger(m) || m < 1 || m > 12) throw new BadRequestException(`Month ${m} is not a month (1-12)`);
    }
    return unique.sort((a, b) => ((a - 8 + 12) % 12) - ((b - 8 + 12) % 12));
}

/** Rupees in whole numbers: what every EC amount must be. */
export function assertWholeRupees(amount: number, label = 'Amount'): number {
    if (!Number.isFinite(amount) || !Number.isInteger(amount)) {
        throw new BadRequestException(`${label} must be a whole number of rupees`);
    }
    return amount;
}
